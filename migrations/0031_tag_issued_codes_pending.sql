-- Issued codes and physical stock, together (3D Printing repo, .claude/plans/2026-10-10-xpot-production-record.md).
--
-- 0028/0029 made a batch an intake container filled by scanning, and every piece stock. In-house 3D printing (and a
-- supplier printing Xpot codes) needs the codes BEFORE the piece exists: the code goes into the print file. So a
-- batch now says where its codes came from, and an issued code that is not a physical piece yet is `pending` stock:
-- it never counts as stock and cannot go into a kit, a sale or an activation until it is scanned into its batch.

ALTER TABLE "tag_batches" ADD COLUMN IF NOT EXISTS "code_source" text NOT NULL DEFAULT 'scanned';
ALTER TABLE "tag_batches" DROP CONSTRAINT IF EXISTS "tag_batches_code_source_check";
ALTER TABLE "tag_batches" ADD CONSTRAINT "tag_batches_code_source_check" CHECK ("code_source" IN ('issued', 'scanned'));
-- Every batch made before 0028 had its codes generated by Xpot.
UPDATE "tag_batches" b SET "code_source" = 'issued'
WHERE EXISTS (SELECT 1 FROM "tags" t WHERE t."batch_id" = b."id");

ALTER TABLE "tags" DROP CONSTRAINT IF EXISTS "tags_stock_status_check";
ALTER TABLE "tags" ADD CONSTRAINT "tags_stock_status_check"
  CHECK ("stock_status" IN ('pending', 'available', 'reserved', 'internal_use', 'sold', 'damaged', 'lost', 'retired'));

ALTER TABLE "tag_stock_movements" DROP CONSTRAINT IF EXISTS "tag_stock_movements_movement_type_check";
ALTER TABLE "tag_stock_movements" ADD CONSTRAINT "tag_stock_movements_movement_type_check" CHECK ("movement_type" IN (
  'migration', 'issue', 'intake', 'transfer', 'return', 'reserve', 'release', 'sale',
  'internal_use', 'damage', 'loss', 'restore', 'retire', 'adjustment'
));

-- The two batches whose print files exist but which are not printed yet (2026-10-10): their pieces are not physical
-- stock. Only untouched house pieces move; anything already sold, given or activated keeps its state.
INSERT INTO "tag_stock_movements" (
  "tag_id", "movement_type", "from_stock_status", "to_stock_status", "from_ownership_type", "to_ownership_type",
  "reference_type", "reference_id", "reason"
)
SELECT t."id", 'adjustment', t."stock_status", 'pending', t."ownership_type", 'company',
       'migration', '0031', 'Code issued for a piece that is not printed yet'
FROM "tags" t
JOIN "tag_batches" b ON b."id" = t."batch_id"
WHERE b."batch_code" IN ('REV-2026-003', 'LPLATE-2026-002')
  AND t."status" = 'inventory' AND t."rep_id" IS NULL AND t."sold_at" IS NULL AND t."stock_status" = 'available';

UPDATE "tags" t
SET "stock_status" = 'pending', "registered_at" = NULL, "stock_updated_at" = now(), "updated_at" = now()
FROM "tag_batches" b
WHERE b."id" = t."batch_id"
  AND b."batch_code" IN ('REV-2026-003', 'LPLATE-2026-002')
  AND t."status" = 'inventory' AND t."rep_id" IS NULL AND t."sold_at" IS NULL AND t."stock_status" = 'available';

-- They will receive their pieces by scanning after printing, so they stay open.
UPDATE "tag_batches" SET "status" = 'open', "updated_at" = now()
WHERE "batch_code" IN ('REV-2026-003', 'LPLATE-2026-002') AND "status" = 'closed';
